using System;

namespace TgLlmBot.Services.Telegram.TypingStatus;

/// <summary>
///     Просьба включить или выключить статус "печатает" в чате от имени одного запроса.
/// </summary>
/// <remarks>
///     <para>
///         Включение и выключение ездят одной командой по одному каналу намеренно. Пока это были два
///         канала с двумя независимыми циклами чтения, порядка между ними не было никакого: стоп,
///         обогнавший свой старт, отменял пустоту, а пришедший следом старт включал печать навсегда.
///         На последовательности "медиа-пайплайн отпечатал - передал эстафету обработчику ответа"
///         это ловилось на каждом втором чате.
///     </para>
///     <para>
///         <see cref="RequestId" /> связывает выключение с его же включением. Печатать в одном чате
///         одновременно просят несколько независимых источников: медиа-пайплайн, обработчик ответа,
///         обработчик рейтинга. Без привязки выключение любого из них гасило печать всем остальным,
///         и длинный ответ оставался без индикатора, стоило по соседству закончиться распознаванию.
///     </para>
/// </remarks>
public record TypingCommand(long ChatId, Guid RequestId, bool IsTyping);
