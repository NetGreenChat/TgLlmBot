namespace TgLlmBot.Services.Media;

/// <summary>
///     Потолки длины описаний вложений.
/// </summary>
/// <remarks>
///     Описание живёт в двух видах. Подробное приходит от vision-модели и нужно ровно один раз -
///     чтобы ответить на сообщение, с которым картинка пришла. Сжатое делает уже основная модель,
///     и именно оно остаётся в истории чата: иначе каждая картинка тащила бы в контекст
///     все 65536 токенов, которые vision-модели разрешено выдать.
/// </remarks>
public static class MediaDescriptionLimits
{
    /// <summary>
    ///     Предохранитель от разошедшейся vision-модели. Её потолок - 65536 токенов, а во сколько
    ///     символов они развернутся, зависит от языка и токенизатора, поэтому берём заведомо больше:
    ///     на любом языке 65536 токенов в мегабайт символов укладываются с запасом.
    /// </summary>
    public const int FullMaxLength = 1_048_576;

    /// <summary>
    ///     Потолок сжатого описания - того, что уезжает в историю с каждым сообщением.
    /// </summary>
    /// <remarks>
    ///     Тем же числом обрезается подробное описание, если сжать его ещё не успели: в истории
    ///     полноразмерному описанию делать нечего ни при каких обстоятельствах.
    /// </remarks>
    public const int ShortMaxLength = 1000;
}
