namespace TgLlmBot.DataAccess.Models;

/// <summary>
///     Источник дополнительной части системного промпта, под которой был сгенерирован ответ бота.
/// </summary>
/// <remarks>
///     Дополнительная просьба ("отвечай на древнерусском") живёт ровно один ответ, но сам ответ
///     остаётся в истории чата навсегда. Без пометки о происхождении стиля модель, читая историю
///     при ответе уже другому пользователю, принимает такой ответ за свой обычный голос и
///     продолжает в той же манере.
/// </remarks>
public enum DbCustomPromptScope
{
    /// <summary>
    ///     Дополнительных просьб не было: сообщение написано в обычном стиле бота. Значение
    ///     по умолчанию - им помечены и все сообщения пользователей, и служебные ответы команд.
    /// </summary>
    None = 0,

    /// <summary>
    ///     Была применена просьба, заданная на весь чат (<c>!role</c>).
    /// </summary>
    Chat = 1,

    /// <summary>
    ///     Была применена персональная просьба автора запроса (<c>!personal_role</c>).
    ///     Её автор лежит в <see cref="DbChatMessage.CustomPromptUserId" />.
    /// </summary>
    Personal = 2
}
